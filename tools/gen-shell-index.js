#!/usr/bin/env node
/* Generate app/shell-index.js — what the first screen needs to know about the corpus,
   without the corpus (FIX-INDIA N2; docs/27).

   Home names tonight's story, counts the places, the courses, the languages and the games,
   and the landing says how many stories there are. Those facts used to cost the whole
   corpus — 94 scripts, 3.15 MB gzipped — before a single pixel. This file carries just
   them: one row per story (id, title, hook, its place, its collection, how many scenes),
   the course and language names, and the counts. It is READ OUT OF the data files by
   evaluating them exactly as the page does, so it cannot disagree with them; stamp.sh
   regenerates it on every build, and tools/check-platform.js fails if it is stale.

   Run: node tools/gen-shell-index.js   (stamp.sh does)
*/
'use strict';
const fs = require('fs'), path = require('path'), vm = require('vm');
const APP = path.join(__dirname, '..', 'app');

function sandbox() {
  const el = () => ({ style: {}, setAttribute() {}, appendChild() {}, addEventListener() {},
    classList: { add() {}, remove() {}, toggle() {} }, getContext: () => null,
    querySelector: () => null, querySelectorAll: () => [] });
  const ctx = { console: { log() {}, warn() {}, error() {} }, Math, Date, JSON,
    setTimeout() {}, clearTimeout() {}, setInterval() {}, navigator: {}, location: { search: '', hash: '' },
    document: { createElement: el, createTextNode: () => ({}), head: el(), body: el(), getElementById: () => null,
      querySelector: () => null, querySelectorAll: () => [], addEventListener() {}, documentElement: el() },
    MutationObserver: function () { this.observe = () => {}; },
    addEventListener() {}, matchMedia: () => ({ matches: false, addEventListener() {} }),
    localStorage: { getItem: () => null, setItem() {} } };
  ctx.window = ctx; ctx.self = ctx;
  vm.createContext(ctx);
  return ctx;
}

/* every script the page can load, shell and groups alike, in page order */
function pageScripts() {
  const html = fs.readFileSync(path.join(APP, 'index.html'), 'utf8');
  return [...html.matchAll(/<script src="([^"?]+)/g)].map(m => m[1])
    .filter(f => !/^(app|shell-index|loader|demo)\.js$/.test(f) && fs.existsSync(path.join(APP, f)));
}

function build() {
  const ctx = sandbox();
  for (const f of pageScripts()) {
    try { vm.runInContext(fs.readFileSync(path.join(APP, f), 'utf8'), ctx, { filename: f }); } catch (e) { /* DOM-only files */ }
  }
  const keys = Object.keys(ctx).filter(k => /^IND_STORIES/.test(k));
  /* the SAME order as app.js's allStories(), so a daily pick lands on the same story */
  const ORDER = ['IND_STORIES', 'IND_STORIES_REGIONAL', 'IND_STORIES_MORE', 'IND_STORIES_SOUTH', 'IND_STORIES_NORTH',
    'IND_STORIES_EAST', 'IND_STORIES_WEST', 'IND_STORIES_NE_A', 'IND_STORIES_NE_B', 'IND_STORIES_MODERN',
    'IND_STORIES_VIGYAN', 'IND_STORIES_DASHAVATARA', 'IND_STORIES_DEVASURA'];
  const missing = keys.filter(k => ORDER.indexOf(k) < 0);
  if (missing.length) throw new Error('a story file app.js does not know about: ' + missing.join(', '));
  const stories = [];
  ORDER.forEach(k => (ctx[k] || []).forEach(s => {
    stories.push([s.id, s.title, s.hook || '', ((s.place || [])[0] || ''), s.collection || '', (s.scenes || []).length,
      s.minutes || 0, s.badge || '']);
  }));
  const packs = Object.keys(ctx.IND_PACKS || {}).map(id => {
    const p = ctx.IND_PACKS[id]; return [id, (p.name && p.name.en) || id, (p.name && p.name.native) || ''];
  });
  const courses = ((ctx.IND_PAATH || {}).courses || []).map(c => [c.id, c.name, !!c.premium]);
  return {
    v: 1,
    places: Object.keys((ctx.IND_MAP || {}).paths || {}).length,
    names: Object.keys(((ctx.IND_GEO || {}).states) || {}).reduce((o, c) => { o[c] = ctx.IND_GEO.states[c].name; return o; }, {}),
    games: (ctx.IND_GAMES || []).length,
    worlds: ((ctx.IND_WORLDS || {}).list || []).length,
    stories, packs, courses
  };
}

if (require.main === module) {
  const idx = build();
  const out = '/* GENERATED by tools/gen-shell-index.js from the data files — do not hand-edit. */\n' +
    'window.IND_INDEX = ' + JSON.stringify(idx) + ';\n';
  fs.writeFileSync(path.join(APP, 'shell-index.js'), out);
  console.log('shell-index: %d stories, %d places, %d packs, %d courses, %d games — %s KB',
    idx.stories.length, idx.places, idx.packs.length, idx.courses.length, idx.games, (out.length / 1024).toFixed(1));
}
module.exports = { build };
