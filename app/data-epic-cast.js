/* Bizzing India — who's who in the two epics.

   WHY THIS FILE EXISTS. The epics were written with almost every principal speaking in the
   storyteller's voice rather than as a named speaker — a deliberate choice, because the art
   set had no Sita, no Draupadi, no Bhishma, and a wrong face is worse than no face. The
   consequence is that `card.who` is set on only about a tenth of the cards, and `episode.cast`
   lists only the handful of characters an avatar already exists for. So the app had no way to
   tell a child who was in the scene it had just described.

   This is that missing layer. It is a registry of the people, keyed by the name as it is
   actually spelled in the card text, so a card can name its own cast by looking at its own
   words. It does not depend on any artwork existing: a character with no avatar still shows
   a name and a line, which is the part a child actually needs.

   `alias` catches the spellings and epithets a card may use instead of the headword.

   EDITORIAL. These descriptions follow the same line the epic files hold. Nobody here is
   introduced as a villain: Ravana is a scholar and a musician who did one unforgivable thing,
   Duryodhana has a real grievance nobody ever dealt with honestly, Kaikeyi is a queen who was
   promised something and asked for it. Where the poem refuses to settle a person, so does the
   line. No caste is named anywhere, which is the rule the Mahabharata file was written under.
   The women get the same weight as the men. */

