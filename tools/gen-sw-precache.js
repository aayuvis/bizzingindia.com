#!/usr/bin/env node
/* Generate app/sw-precache.js — the service worker's core file list.
 *
 * The list is READ OUT OF index.html (every script and stylesheet it loads) plus
 * the fonts, the manifest and the icons, so a new data file added to the page is
 * in the next deploy's offline shell automatically and nobody maintains a list
 * by hand — a hand-kept list is how one missing file quietly breaks offline for
 * a month. Media (voice/, art/) is deliberately absent: that is the pack
 * downloader's job.
 *
 * Run by tools/deploy.sh after stamp.sh (the list carries the ?v= stamps).
 */
'use strict';
const fs = require('fs'), path = require('path');

const APP = path.join(__dirname, '..', 'app');
const html = fs.readFileSync(path.join(APP, 'index.html'), 'utf8');

const urls = new Set(['./index.html', './manifest.webmanifest', './icon-192.png', './favicon-32.png']);
/* NOTHING BEYOND THE SHELL BEFORE A TAP (audit R2/R3, 3 Oct 2026). The worker used to precache
   every script index.html names, the lazy groups included — stories, epics, games, about 11 MB
   — at install, on a first visit, before the child had touched anything: 6.5 MB on a phone
   against a 1.5 MB budget. A <template id="lazy-…"> group's scripts are not the shell, so they
   go in the second list, which the worker fetches only when the page says the child has
   started (loader.js, after the first tap). */
const lazySrc = new Set();
for (const t of html.match(/<template id="lazy-[^"]+">[\s\S]*?<\/template>/g) || []) {
  for (const mm of t.matchAll(/src="([^"]+)"/g)) lazySrc.add('./' + mm[1].replace(/^\.\//, ''));
}
const re = /(?:src|href)="([^"]+)"/g;
let m;
while ((m = re.exec(html))) {
  const u = m[1];
  if (/^https?:/.test(u)) continue;
  if (u.indexOf('voice/') === 0 || u.indexOf('art/') === 0) continue;
  const k = './' + u.replace(/^\.\//, '');
  if (!lazySrc.has(k)) urls.add(k);
}
/* the family's shared modules are IMPORTED by family/bridge.js, so index.html never names
   them — list the folder, or the offline shell boots with no wallet */
for (const f of fs.readdirSync(path.join(APP, 'family'))) {
  if (/\.(js|css)$/.test(f)) urls.add('./family/' + f);
}
/* THE PER-SCRIPT FACES AND THE READING PASSAGES WAIT (FIX-INDIA R2; standard §9, §18). A
   browser fetches a face only when a glyph in its range is drawn, so a first visit costs only
   the faces its first screen uses — but the worker used to fetch ALL of them at install, about
   1.2 MB of woff2 on a first visit. They go in a second list the worker fetches quietly, a
   while after it has taken over, so the app still works offline in every script. */
const later = new Set();
for (const f of fs.readdirSync(path.join(APP, 'font'))) {
  if (!f.endsWith('.woff2')) continue;
  (/^(mukta|noto)/.test(f) ? later : urls).add('./font/' + f);
}
for (const u of lazySrc) later.add(u);
/* the big install icons are the launcher's, not the first screen's: after the first tap */
for (const u of ['./icon-512.png', './icon-maskable-512.png', './apple-touch-icon.png']) later.add(u);
for (const u of [...urls]) if (/data-bhasha-hi-passages\.js|data-feed-(?!index)[^/]*\.js/.test(u)) { urls.delete(u); later.add(u); }
/* the music is lazy too: composed in code, fetched only when a child turns it on */
if (fs.existsSync(path.join(APP, 'music', 'engine.js'))) later.add('./music/engine.js');
/* the logo the header shows on first paint */
if (fs.existsSync(path.join(APP, 'art', 'logo.png'))) urls.add('./art/logo.png');

const list = [...urls].sort();
let bytes = 0;
for (const u of list) {
  const p = path.join(APP, u.replace(/^\.\//, '').replace(/\?.*$/, ''));
  if (fs.existsSync(p)) bytes += fs.statSync(p).size;
}
fs.writeFileSync(path.join(APP, 'sw-precache.js'),
  '/* GENERATED by tools/gen-sw-precache.js from index.html — do not hand-edit. */\n' +
  'self.IND_PRECACHE = ' + JSON.stringify(list) + ';\n' +
  'self.IND_PRECACHE_LATER = ' + JSON.stringify([...later].sort()) + ';\n');
console.log('sw-precache: %d files, %s MB', list.length, (bytes / 1048576).toFixed(1));
