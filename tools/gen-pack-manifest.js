#!/usr/bin/env node
/* Generate app/pack-manifest.js — what the audio/art packs contain and weigh.
 *
 * The downloader (app/downloads.js) is a dumb loop over this manifest: fetch each
 * file into the shared 'ind-media-v1' cache with a progress count. The manifest is
 * generated from the files actually on disk, so a re-narration or a new story is
 * in the next deploy's pack automatically and the advertised MB is the truth.
 *
 * Pack boundaries are PRODUCT boundaries (docs/06): the story library's audio is
 * the big paid download; each language is its own pack; art rides separately so a
 * family on a tight data plan can choose sound first.
 */
'use strict';
const fs = require('fs'), path = require('path');

const APP = path.join(__dirname, '..', 'app');

function walk(dir, keep) {
  const root = path.join(APP, dir);
  if (!fs.existsSync(root)) return [];
  const out = [];
  (function rec(d) {
    for (const f of fs.readdirSync(d)) {
      const p = path.join(d, f);
      if (fs.statSync(p).isDirectory()) { rec(p); continue; }
      const rel = path.relative(APP, p).split(path.sep).join('/');
      if (!keep || keep(rel)) out.push(rel);
    }
  })(root);
  return out.sort();
}
function bytes(files) {
  return files.reduce((a, f) => a + fs.statSync(path.join(APP, f)).size, 0);
}

const LANGS = { hi: 'Hindi', pa: 'Punjabi', bn: 'Bengali', mr: 'Marathi', te: 'Telugu',
                ta: 'Tamil', gu: 'Gujarati', ur: 'Urdu', kn: 'Kannada' };

const packs = {};
packs['stories-en'] = { name: 'Story narration · English', group: 'Stories',
  files: walk('voice/st', f => !/-hi\.mp3$/.test(f)) };
packs['stories-hi'] = { name: 'Story narration · Hindi', group: 'Stories',
  files: walk('voice/st', f => /-hi\.mp3$/.test(f)) };
packs['epics-en'] = { name: 'Ramayana & Mahabharata · English', group: 'Stories',
  files: walk('voice/ep', f => !/-hi\.mp3$/.test(f)) };
packs['epics-hi'] = { name: 'Ramayana & Mahabharata · Hindi', group: 'Stories',
  files: walk('voice/ep', f => /-hi\.mp3$/.test(f)) };
for (const [code, name] of Object.entries(LANGS)) {
  const files = walk('voice/' + code);
  if (files.length) packs['lang-' + code] = { name: name + ' · letters, words & talk', group: 'Languages', files };
}
packs['art-stories'] = { name: 'Story paintings', group: 'Art', files: walk('art/story') };
packs['art-epics'] = { name: 'Epic card paintings', group: 'Art', files: walk('art/epic') };

const out = {};
for (const [id, p] of Object.entries(packs)) {
  out[id] = { name: p.name, group: p.group, n: p.files.length,
              mb: +(bytes(p.files) / 1048576).toFixed(1), files: p.files };
}
fs.writeFileSync(path.join(APP, 'pack-manifest.js'),
  '/* GENERATED by tools/gen-pack-manifest.js from the files on disk — do not hand-edit. */\n' +
  'window.IND_PACKS_DL = ' + JSON.stringify(out) + ';\n');
for (const [id, p] of Object.entries(out))
  console.log('  %s  %s files  %s MB  — %s', id.padEnd(12), String(p.n).padStart(5), String(p.mb).padStart(7), p.name);
