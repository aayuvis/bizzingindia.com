#!/usr/bin/env node
/* gen-voice-manifest.js — rebuild app/voice-manifest.js from the files on disk.
 *
 *   node tools/gen-voice-manifest.js
 *
 * The manifest used to be written only by tools/tts.py, which meant a clip that
 * arrived from anywhere else — a human recording session, say — was invisible to
 * the app no matter how good it was. Rebuilding from disk is the only version
 * that cannot lie, the same reason gen-art-manifest.py exists.
 *
 * TWO REGISTRIES, because they are two different promises:
 *
 *   IND_VOICE        every clip that exists, keyed. The existing contract; the
 *                    app checks it before trying to play anything.
 *
 *   IND_VOICE_HUMAN  the ones a PERSON recorded, with which voices exist and
 *                    what container they are in:
 *                        "hi/d-01-p": { e: "webm", v: "fm" }
 *                    The app prefers these over the synthesised clip and picks
 *                    a voice; docs/09 §9 is explicit that synthesised Indic
 *                    speech teaches errors, so "is this a human?" has to be a
 *                    fact the runtime can read, not a note in a commit.
 */
'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const VOICE = path.join(ROOT, 'app', 'voice');
const OUT = path.join(ROOT, 'app', 'voice-manifest.js');

const AUDIO = /\.(mp3|webm|ogg|m4a)$/i;
/* a human take is <key>-<voice>.<ext>; anything else in the tree is synthesised */
const HUMAN = /^(.*)-([fm])$/;

function walk(dir, base, out) {
  for (const name of fs.readdirSync(dir)) {
    if (name.startsWith('.')) continue;
    const full = path.join(dir, name);
    const st = fs.statSync(full);
    if (st.isDirectory()) { walk(full, base ? base + '/' + name : name, out); continue; }
    if (!AUDIO.test(name)) continue;
    const stem = name.replace(AUDIO, '');
    const ext = name.slice(name.lastIndexOf('.') + 1).toLowerCase();
    out.push({ key: (base ? base + '/' : '') + stem, ext, bytes: st.size });
  }
}

function main() {
  if (!fs.existsSync(VOICE)) { console.log('no app/voice directory — nothing to do'); return; }
  const files = [];
  walk(VOICE, '', files);

  const keys = new Set();
  const human = {};          /* baseKey -> { e: ext, v: 'f' | 'm' | 'fm' } */
  let humanBytes = 0;

  for (const f of files) {
    const m = HUMAN.exec(f.key);
    if (m) {
      const base = m[1], voice = m[2];
      const rec = human[base] || (human[base] = { e: f.ext, v: '' });
      if (rec.v.indexOf(voice) < 0) rec.v += voice;
      humanBytes += f.bytes;
      keys.add(base);        /* the app asks for the BASE key; voice is a file detail */
    } else {
      keys.add(f.key);
    }
  }

  const sorted = [...keys].sort();
  const hkeys = Object.keys(human).sort();
  /* 'fm' reads better than 'mf' and the app tests by indexOf, so normalise */
  for (const k of hkeys) human[k].v = human[k].v.split('').sort().join('');

  const body =
`/* Bizzing India — bundled narration index. GENERATED by tools/gen-voice-manifest.js
   from the files actually on disk; do not hand-edit.

   IND_VOICE        every clip that exists.
   IND_VOICE_HUMAN  the ones a person recorded — { e: container, v: voices }.
                    The app prefers a human take over the synthesised one and
                    picks a voice from \`v\`.

   English story narration is en-IN-Chirp3-HD-Laomedeia at rate 1.02 — an Indian
   narrator, which is the whole point; the old en-US voice read the names as a
   foreigner would. <phoneme> tags from tools/pron-lexicon.json where the voice
   supports SSML. Hindi/Punjabi letters and words are still TTS
   placeholders — per docs/09 §9 these MUST be replaced with human voice before
   launch, because children imitate them. The dialogue lines are the first part
   of that replacement (tools/studio.js). */

window.IND_VOICE = ${JSON.stringify(sorted)};

window.IND_VOICE_HUMAN = ${JSON.stringify(human, null, 0)};
`;

  const before = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  fs.writeFileSync(OUT, body);
  const note = `voice-manifest.js: ${sorted.length} clips, ${hkeys.length} human ` +
               `(${Math.round(humanBytes / 1024)} kB)`;
  console.log(before === body ? note + ' — unchanged' : note);
}

main();
